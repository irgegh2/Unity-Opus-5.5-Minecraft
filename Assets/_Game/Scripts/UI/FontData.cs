        public static ushort[] Glyph(char c) => glyphs.TryGetValue(c, out var g) ? g : glyphs['?'];

        /// <summary>First lit column and pixel width of a glyph (proportional spacing).</summary>
        public static (int left, int width) Metrics(char c) => metrics.TryGetValue(c, out var m) ? m : metrics['?'];

        public static int CharAdvance(char c) => c == ' ' ? 4 : Metrics(c).width + 1;

        /// <summary>Pixel width of a single line of text, ignoring colour codes (section sign + one char).</summary>
        public static int Width(string s)
        {
            if (string.IsNullOrEmpty(s)) return 0;
            int w = 0, best = 0;
            for (int i = 0; i < s.Length; i++)
            {
                char c = s[i];
                if (c == '§' && i + 1 < s.Length) { i++; continue; }
                if (c == '\n') { best = Mathf.Max(best, w); w = 0; continue; }
                w += CharAdvance(c);
            }
            return Mathf.Max(best, w) - 1;
        }

        /// <summary>Number of visible lines.</summary>
        public static int LineCount(string s) => string.IsNullOrEmpty(s) ? 1 : s.Split('\n').Length;
