        static void G(char c, params ushort[] rows)
        {
            // 7-row glyphs sit on the baseline; an 8th row is the descender
            var r = new ushort[GlyphH];
            for (int i = 0; i < rows.Length && i < GlyphH; i++) r[i] = rows[i];
            glyphs[c] = r;
            int min = 5, max = -1;
            foreach (var row in r)
                for (int b = 0; b < 5; b++)
                    if ((row & (1 << (4 - b))) != 0) { if (b < min) min = b; if (b > max) max = b; }
            metrics[c] = max < 0 ? (0, 3) : (min, max - min + 1);
        }

